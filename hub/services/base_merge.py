"""Мерж базы в ветку: что он стоит человеку, и что гейт вправе решить сам (#1233).

09.09.2026 #1204 была одобрена в 05:48 и через четырнадцать секунд получила
merge_failed: конфликт с только что доставленной #1205 в трёх файлах. Задача
ушла в needs_decision, исполнитель слил базу, разрешил конфликты и пересдался —
и тот же человек должен одобрить ту же работу второй раз. Один мерж стоил двух
вердиктов.

Здесь живут два ПРАВИЛА, оба механические, и оба нарочно узкие.

1. ВЕРДИКТ ПЕРЕЖИВАЕТ МЕРЖ БАЗЫ, если авторская работа не изменилась. Признак —
   в ``git diff <base>...<tip>`` до мержа и после совпадают по каждому файлу
   упорядоченные строки +/- (``author_edit_same``, #1361; до него — байт в
   байт). Никакого доверия к сообщению коммита: сообщение — это заявление, а
   дифф — наблюдение. Тем же правилом заказ ревью решает, покупать ли новый
   прогон на пересдаче «только слита база».

2. АВТОМЕРЖ ТОЛЬКО ОДНОГО КЛАССА КОНФЛИКТА: обе стороны лишь ДОБАВИЛИ строки в
   конец одного файла, ничего общего не тронув. Признак берётся у самого git:
   в разметке diff3 у такого конфликта ПУСТАЯ секция общего предка — значит,
   ни одна сторона не переписала ни одной существующей строки. Всё остальное,
   включая смысловой случай #1204, остаётся человеку.

Порядок разрешения — «сначала наше, потом привезённое» — не косметика: авторский
блок остаётся на своём месте, а привезённое дописывается за ним. Ничего чужого
поверх авторского кода не ложится.

Правило 1 НЕ покрывает случай правила 2, и это проверено делом
(tests/test_delivery_gate.py, настоящий git). До #1361 причиной были строка
``index`` и смещения ханков; их правило 1 теперь отбрасывает, но на хвостовых
добавлениях git сдвигает пустые строки, и последовательность +/- автора
выходит другой. Поэтому вердикт после АВТОмержа держится не на сравнении
диффов, а на том, что коммит сделал сам гейт: он перезакрепляет коммит сдачи и
говорит об этом вслух. Сравнение диффов остаётся для чужих мержей, где
ручаться не за что.
"""

from __future__ import annotations

# Классы конфликта. ``unresolvable`` — это не «плохо», а «не наш класс»: гейт
# зовёт человека и называет причину, как и раньше.
TAIL_ADDITIONS = "tail_additions"
UNRESOLVABLE = "unresolvable"

_OURS = "<<<<<<<"
_BASE = "|||||||"
_THEIRS = "======="
_END = ">>>>>>>"


def _author_edit(diff: str) -> dict[str, list[str]]:
    """Авторская правка по файлам: упорядоченные строки +/- и заголовки смысла.

    Ключ — строка ``diff --git a/… b/…``: переименование меняет ключ и потому
    читается как изменение. Отбрасывается только то, что сдвигает мерж базы
    при неизменной работе автора: строки ``index`` (блоб базы другой),
    заголовки ханков ``@@`` (вставка базы сдвигает смещения), ``---``/``+++``
    (пути уже в ключе), ``similarity index`` и строки контекста.

    Всё прочее остаётся В ПОРЯДКЕ ПОЯВЛЕНИЯ: ``+``/``-`` вместе с содержимым,
    смена режима, создание, удаление, переименование. У бинарного файла строк
    +/- нет, его содержимое видно только по ``index`` — поэтому у бинарного
    файла строка ``index`` остаётся. Лишнее расхождение уронит вердикт, а
    пропущенное сохранило бы его над подменённой картинкой.
    """
    files: dict[str, list[str]] = {}
    index: dict[str, str] = {}
    key = ""
    for line in diff.splitlines():
        if line.startswith("diff --git "):
            key = line[len("diff --git ") :]
            files.setdefault(key, [])
            continue
        if line.startswith("index "):
            index[key] = line
            continue
        if line.startswith(("@@", "--- ", "+++ ", "similarity index ")) or (
            line.startswith("dissimilarity index ")
        ):
            continue
        if not line or line.startswith(" "):
            continue
        files.setdefault(key, []).append(line)
    for name, lines in files.items():
        if name in index and any(ln.startswith("Binary files ") for ln in lines):
            lines.insert(0, index[name])
    return files


def _file_name(key: str) -> str:
    """``a/x b/y`` → ``y`` (или ``x → y`` при переименовании) для причины."""
    parts = key.split(" b/", 1)
    if len(parts) != 2:
        return key or "(без заголовка)"
    old, new = parts[0].removeprefix("a/"), parts[1]
    return new if old == new else f"{old} → {new}"


def author_edit_same(before: str | None, after: str | None) -> tuple[bool, str]:
    """Та же ли авторская правка до и после мержа базы (#1233, #1361).

    ОДНО правило на двух потребителей: гейт доставки решает им, пережил ли
    вердикт сдвиг вершины, а заказ ревью — нужен ли новый прогон на
    пересдаче. Второго правила нет и заводить его нельзя: два ответа на
    вопрос «правил ли автор» рано или поздно разойдутся.

    ``before`` и ``after`` — ``git diff -U0 <base>...<tip>`` двух вершин.
    Сравниваются ПО ФАЙЛАМ упорядоченные последовательности строк +/-
    (``_author_edit``), а не байты: мерж базы в тот же файл меняет строку
    ``index`` и смещения ханков, не трогая ни одной авторской строки, и
    побайтное сравнение (#1233) слетало ровно на тех слияниях, ради которых
    существовало. 23.09.2026: #1242, #1254, #1333, #1334, #1337.

    Упорядоченные, а не множество: перестановка авторских строк — смысл (в
    #1337 миграция переехала в конец списка). Строка разрешения конфликта,
    которой не было, — новая авторская правка, и вердикт слетает.

    Известная граница: без контекста не видно, КУДА в файле встал авторский
    блок. Разрешение, переносящее неизменный блок в другое место того же
    файла без единой другой строки, прочтётся как та же правка. Контекст
    сюда не берётся намеренно — его меняет сама база, и правило вернулось бы
    к побайтовому.

    ``None`` — «посмотреть не удалось», и за совпадение оно НЕ засчитывается:
    недоступный git не продлевает вердикт на код, которого никто не видел.
    """
    if before is None or after is None:
        return False, "дифф ветки к базе прочитать не удалось — сверять нечего"
    old, new = _author_edit(before), _author_edit(after)
    changed = sorted(
        _file_name(k) for k in set(old) | set(new) if old.get(k) != new.get(k)
    )
    if changed:
        return False, (
            "авторская правка изменилась — в ветке есть авторская правка сверх "
            "одобренной: " + ", ".join(changed)
        )
    return True, (
        "авторская правка та же: строки +/- по каждому файлу совпали в том же "
        "порядке, мерж привёз только базу"
    )


def _regions(text: str) -> list[tuple[int, int]] | None:
    """Границы конфликтных участков (индексы строк ``<<<<<<<`` и ``>>>>>>>``).

    ``None``, если разметка не разобралась: вложенный или оборванный маркер —
    это повод позвать человека, а не угадывать.
    """
    lines = text.splitlines()
    out: list[tuple[int, int]] = []
    start = -1
    for i, line in enumerate(lines):
        if line.startswith(_OURS):
            if start >= 0:
                return None
            start = i
        elif line.startswith(_END):
            if start < 0:
                return None
            out.append((start, i))
            start = -1
    if start >= 0:
        return None
    return out


def classify_conflict(text: str) -> tuple[str, str]:
    """Класс конфликта одного файла по разметке diff3 (#1233, AC-3/AC-4).

    Возвращает ``(класс, причина)``. ``TAIL_ADDITIONS`` — единственный класс,
    который гейт разрешает сам: ровно один участок, пустая секция общего предка
    (обе стороны только добавляли) и участок стоит в конце файла. Причина
    заполнена всегда, в том числе у разрешимого класса: «что именно сложено»
    обязано быть видно в карточке, а не выводиться читателем.
    """
    regions = _regions(text)
    if regions is None:
        return UNRESOLVABLE, "разметку конфликта не удалось разобрать"
    if len(regions) != 1:
        return UNRESOLVABLE, (
            f"участков конфликта {len(regions)}, а автомерж умеет только один"
        )
    lines = text.splitlines()
    start, end = regions[0]
    body = lines[start + 1 : end]
    if not any(ln.startswith(_BASE) for ln in body):
        # Без секции общего предка нельзя доказать, что ничего не переписано.
        return UNRESOLVABLE, "конфликт записан без общего предка (нужна разметка diff3)"
    ancestor_at = next(i for i, ln in enumerate(body) if ln.startswith(_BASE))
    theirs_at = next((i for i, ln in enumerate(body) if ln.startswith(_THEIRS)), -1)
    if theirs_at < ancestor_at:
        return UNRESOLVABLE, "разметку конфликта не удалось разобрать"
    ancestor = body[ancestor_at + 1 : theirs_at]
    if [ln for ln in ancestor if ln.strip()]:
        return UNRESOLVABLE, (
            "обе стороны правят одни и те же строки — это разрешает человек"
        )
    if [ln for ln in lines[end + 1 :] if ln.strip()]:
        return UNRESOLVABLE, "конфликт не в конце файла — это разрешает человек"
    if not [ln for ln in lines[:start] if ln.strip()]:
        # ХВОСТ БЫВАЕТ ТОЛЬКО У ЧЕГО-ТО. Пустая секция общего предка означает
        # «ни одна сторона не переписала существующей строки» лишь тогда, когда
        # существующие строки вообще были: они стоят НАД маркером. Если над
        # маркером пусто, предка нет не потому, что его берегли, а потому, что
        # файла не было — обе стороны завели ОДИН путь заново (add/add).
        #
        # Проверено на настоящем git: ветка и база создали каждая свой thing.py,
        # diff3 дал пустого предка и ничего до маркера, класс выходил
        # «хвостовые добавления», и «оставить оба» склеивало два целых файла — а
        # в Python побеждает последнее определение, то есть версия базы молча
        # переписывала авторскую (handle(1) вернул 100 вместо 2). Это прямо
        # против ограничения постановки «не меняется авторский код».
        return UNRESOLVABLE, (
            "до конфликта в файле нет ни строки — обе стороны завели этот путь "
            "заново, и «оставить оба» склеило бы два разных файла; это человек"
        )
    ours = body[:ancestor_at]
    theirs = body[theirs_at + 1 :]
    return TAIL_ADDITIONS, (
        f"хвостовые добавления: {len(ours)} строк из ветки и {len(theirs)} "
        f"из базы, ничего не переписано"
    )


def resolve_tail_additions(text: str) -> str | None:
    """«Оставить оба» для класса ``TAIL_ADDITIONS``; ``None`` для всех прочих.

    Наше идёт первым — см. модульную строку: этот порядок сохраняет смещение
    авторского блока, а с ним и вердикт.
    """
    if classify_conflict(text)[0] != TAIL_ADDITIONS:
        return None
    lines = text.splitlines()
    regions = _regions(text) or []
    start, end = regions[0]
    body = lines[start + 1 : end]
    ancestor_at = next(i for i, ln in enumerate(body) if ln.startswith(_BASE))
    theirs_at = next(i for i, ln in enumerate(body) if ln.startswith(_THEIRS))
    merged = (
        lines[:start] + body[:ancestor_at] + body[theirs_at + 1 :] + lines[end + 1 :]
    )
    trailing = "\n" if text.endswith("\n") else ""
    return "\n".join(merged) + trailing


def plan_resolution(files: dict[str, str]) -> tuple[dict[str, str], str]:
    """Разрешение всего конфликта целиком, или отказ с названной причиной.

    Возвращает ``(разрешения, причина)``. Непустая причина при пустых
    разрешениях — это отказ: класс не наш, задача идёт к человеку. Правило
    «целиком»: хватает ОДНОГО файла вне класса, чтобы не трогать ни один, —
    полуразрешённый мерж хуже неразрешённого.
    """
    if not files:
        return {}, "конфликтующих файлов не названо"
    resolutions: dict[str, str] = {}
    notes: list[str] = []
    for path in sorted(files):
        kind, why = classify_conflict(files[path])
        if kind != TAIL_ADDITIONS:
            return {}, f"{path}: {why}"
        merged = resolve_tail_additions(files[path])
        if merged is None:  # pragma: no cover - classify уже сказал «да»
            return {}, f"{path}: разрешение не собралось"
        resolutions[path] = merged
        notes.append(f"{path} — {why}")
    return resolutions, "; ".join(notes)
