"""Гейты перехода — объявленный список, а не цепочка if-ов (#1067).

ЗАЧЕМ. ``submit_for_review`` читалась как хронология тикетов: #305 сдача pair,
#533 сверка ветки, #583 дифф и риск-класс, #550/#890 поверхности, #911 исходы
находок, #855 правила сдачи, #572 пиннинг SHA, #605/#967/#975 обнаружение PR,
#1054 пересдача из review. Каждый новый гейт ложился следующим блоком в ту же
функцию — контекст уже собран выше, порядок важен, так дешевле. К #1067 она
выросла до 538 строк при цикломатике 46, и правка любого гейта стала правкой
этой функции целиком.

ЧТО ЗДЕСЬ. Только механизм: запись шага и прогон списка. Сами шаги живут
рядом со своими помощниками — ``_resolve_branch_diff``, ``_surface_check``,
``resolve_branch_tip`` объявлены в ``hub.services.lifecycle`` и уже
импортируются оттуда пятью модулями, так что шаги, вынесенные сюда, замкнули
бы импорт в кольцо. Механизм ничего из домена не знает и потому импортов не
имеет вовсе.

ПОЧЕМУ СПИСОК, А НЕ ПОРЯДОК IF-ОВ. Порядок остаётся несущим — он и был
несущим, — но перестаёт держаться тем, что никто не переставил блоки. Список
можно сверить тестом, показать в отчёте и сравнить с другим списком: именно
так видно, что pair-путь и headless-путь проверяют разное.

Образец приёма в этом же репозитории: ``hub/lifecycle_matrix.py`` — таблица
плюс тесты покрытия, краснеющие на новом члене enum.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from typing import Any, Generic, TypeVar

Ctx = TypeVar("Ctx")

# Значения политики, при которых шаг вообще не выполняется. Разбор warn против
# require оставлен самому шагу: смысл у них разный от шага к шагу — где-то это
# отказ против заметки, где-то ещё и другой текст.
OFF = "off"
# Режим безусловного шага. Не "on" ради красоты: у шага без политики нет
# состояния "выключен", и это должно быть видно в отчёте, а не подразумеваться.
ALWAYS = "always"


@dataclass(frozen=True)
class Step(Generic[Ctx]):
    """Один шаг конвейера перехода.

    ``mode`` — вызываемое, возвращающее режим шага: политика читается в момент
    прогона, а не в момент объявления списка. Список объявляется на импорте
    модуля, а политики живут в ``hub.config`` и меняются переменными
    окружения; заморозить режим на импорте значило бы, что смена политики не
    действует до перезапуска, и это разошлось бы с остальными SDD-проверками.

    ``refuses`` — объявление намерения, а не поведение. Шаг с ``False``
    производит контекст и отказывать не имеет права; читается тестом сверки и
    человеком, который добавляет следующий шаг. Механизм это не навязывает:
    страж, который ловил бы попытку отказа, стоил бы дороже, чем стоит сам
    факт, а список читают глазами чаще, чем нарушают.
    """

    name: str
    run: Callable[[Ctx], Awaitable[None]]
    mode: Callable[[], str] = lambda: ALWAYS
    refuses: bool = True

    def describe(self) -> dict[str, Any]:
        """Строка отчёта: имя, режим сейчас, право отказывать."""
        return {"name": self.name, "mode": self.mode(), "refuses": self.refuses}


async def run_steps(ctx: Ctx, steps: tuple[Step[Ctx], ...]) -> None:
    """Прогнать конвейер по порядку. Отказ прерывает прогон.

    Прерывание на первом отказе — часть контракта, а не деталь реализации:
    дальше по списку идут сетевые резолвы (дифф ветки, её tip, обнаружение
    PR), и гонять их ради отказа, который уже случился, значит платить за него
    временем и сетью. Ровно так вела себя цепочка if-ов, которую список
    заменяет.

    Отказ выражается исключением — тем же ``HTTPException``, что и раньше, с
    тем же кодом и текстом. Свой тип результата здесь был бы вторым способом
    сказать то же самое и потребовал бы переписать каждый отказ, то есть внёс
    бы риск ровно туда, где задача обещала его не вносить.
    """
    for step in steps:
        if step.mode() == OFF:
            continue
        await step.run(ctx)


def policy(name: str, default: str = "warn") -> Callable[[], str]:
    """Режим по имени политики в ``hub.config``, читаемый на каждом прогоне.

    Отдельная функция, а не лямбда на месте: политику читают три конвейера
    (сдача, вердикт, headless), и нормализация — strip и lower — должна быть
    одна. Незаданная политика значит ``warn``: это уже действующее правило
    хаба, здесь оно только собрано в одном месте.
    """

    def read() -> str:
        from hub import config

        return (getattr(config, name, None) or default).strip().lower()

    return read
