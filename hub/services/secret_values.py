"""Сканер значений секретов для доказательств задачи-состояния (#1647).

Доказательство сдачи — свободный текст «что выполнил и что увидел». На проде в
такой текст легко попадает вывод команды вместе с ключом. Этот модуль ищет в
тексте ЗНАЧЕНИЯ по точным шаблонам и называет сработавший шаблон, но не
возвращает найденное.

ДОПОЛНИТЕЛЬНОЕ ОГРАНИЧЕНИЕ, А НЕ ГАРАНТИЯ. Сканер знает конечный набор форм:
секрет в другой форме пройдёт. Защита держится на правиле для отправителя —
передавать обезличенные наблюдения («ключ принят, 200»), — а сканер только
ловит самую вероятную ошибку исполнения этого правила. Поэтому ответ хаба об
отказе называет вид ошибки и поле, но не значение (hub.services.state_task), а
тело запроса и evidence не пишутся в лог.

Без зависимостей: модуль зовётся из сервиса сдачи и из тестов шаблонов.
"""

from __future__ import annotations

import re

#: (имя шаблона, регулярное выражение). Имя — то, что узнаёт отправитель;
#: порядок — порядок проверки, первый сработавший побеждает.
PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("openai_style_key", re.compile(r"\bsk-[A-Za-z0-9_\-]{16,}")),
    ("github_token", re.compile(r"\bghp_[A-Za-z0-9]{36}\b")),
    ("github_pat", re.compile(r"\bgithub_pat_[A-Za-z0-9_]{22,}")),
    ("aws_access_key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("slack_token", re.compile(r"\bxox[abprs]-[A-Za-z0-9\-]{10,}")),
    ("bearer_token", re.compile(r"\bBearer\s+[A-Za-z0-9._~+/=\-]{16,}")),
    ("private_key_block", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    (
        "assigned_secret",
        re.compile(
            r"(?i)(?<![A-Za-z0-9])[A-Za-z0-9_.\-]*(?:KEY|TOKEN|SECRET|PASSWORD)"
            r"[ \t]*=[ \t]*\S+"
        ),
    ),
)


def find_secret(text: str) -> str:
    """Имя первого сработавшего шаблона или пустая строка.

    Значение не возвращается и не логируется: имя шаблона — единственное, что
    уходит наружу.
    """
    if not text:
        return ""
    for name, pattern in PATTERNS:
        if pattern.search(text):
            return name
    return ""
