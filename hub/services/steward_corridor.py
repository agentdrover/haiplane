"""Неразрешённая находка — это незаданный вопрос, а не чистота (#1234).

ЗАМЕР, ПОВТОРЁННЫЙ ДВАЖДЫ. Ранее по пяти отчётам (#163-#167): тринадцать
ПОДТВЕРЖДЁННЫХ находок, ни одна не оказалась настоящей, — и шесть
НЕРАЗРЕШЁННЫХ, настоящими оказались все шесть. 09.09.2026 замер повторён на
новых данных: из семи неразрешённых настоящими оказались шесть. Один и тот
же вывод двумя независимыми выборками: раздел ``unresolved`` — самый
урожайный источник настоящих дефектов из всего, что даёт машинное ревью.

И ЕДИНСТВЕННЫЙ, КОТОРОГО КОНТУР НЕ ВИДЕЛ. Отчёт с нулём подтверждённых и
непустым ``unresolved`` читался всеми поверхностями как «находок нет»:
карточка печатала «0 / N подтверждено из сырых», квитанция ревью —
«0 confirmed / N rejected», дайджест не показывал раздел вовсе. Блокировать
автоодобрение хаб уже умел (#1170, ``gate_grounds.unattended_blockers``) —
но молча. Молчаливый отказ и чистый отчёт для читателя неразличимы, и
09.09.2026 три задачи (#1158 с шестью неразрешёнными, #1171 с пятью, #1208
с четырьмя) пришлось разбирать вручную, задание за заданием.

Здесь живут две вещи, и они намеренно разные по природе.

**ЛЕСТНИЦА ИСХОДОВ ОТЧЁТА.** Отчёт стоит на одной названной ступени, и
только у ОДНОЙ из них есть право называться чистотой. Ступень выводится в
одном месте, потому что читателей у неё трое — карточка, дайджест и
квитанция ревью — и три описания одного правила разъезжаются ровно так, как
разъехались бы пять громких оснований, если бы их не свели в
``gate_grounds`` (#1147). Разъезжается при этом тот, который мягче: правило,
добавленное в одну поверхность и забытое в двух, тихо возвращает «чисто»
туда, откуда его убирали.

**МЕХАНИЧЕСКИЙ ШАГ ПЕРЕД ЭСКАЛАЦИЕЙ.** Прежде чем звать человека, стюард
делает то, что умеет сам: применяет мутацию, названную самой находкой, и
гоняет набор. Тест упал — находка настоящая, и это доказательство, а не
голос. Набор зелёный — находка означает непокрытый случай, и это тоже
ответ. Ни один из двух исходов не требует человека.

ПОЧЕМУ ИМЕННО МУТАЦИЯ, А НЕ ЧТЕНИЕ. 09.09.2026 все шесть настоящих
неразрешённых были доказаны или опровергнуты ровно этим приёмом, и ни одна —
рассуждением. Образец: находка «путь записи полей из карточки может выдать
автоодобрение при всех зелёных тестах» опровергалась чтением и подтвердилась
опытом — мутация пережила все 3475 тестов набора.

ГРАНИЦА, КОТОРУЮ ЗДЕСЬ НЕ ПЕРЕХОДЯТ. Неразрешённая находка — это НЕ
подтверждённая находка. Приравнять их значило бы заставить автора отвечать
за то, в чём ревьюер сам не сошёлся. Подтверждённой становится только та,
под которой УПАЛ ТЕСТ: голосование в подтверждение не превращается ни при
каком числе голосов. Адъюдикация внутри харнесса при этом не отменяется и не
переписывается — шаг стоит ПОСЛЕ неё и разбирает ровно то, на чём она не
сошлась.

И стюард здесь ничего не чинит. Он ставит зонд и записывает наблюдение;
мутация обязана откатиться, а дерево после шага — быть чистым. Дерево,
вернувшееся грязным, — это отказ шага, а не его результат: наблюдение,
снятое над неизвестно каким деревом, ничего не наблюдает.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Callable, Mapping, Sequence


# ---------------------------------------------------------------------------
# Лестница исходов отчёта
# ---------------------------------------------------------------------------

#: Прогон не доехал. «Ноль находок на оборванном прогоне» — это «не
#: проверено», а не «чисто» (#549).
OUTCOME_INCOMPLETE = "incomplete_run"

#: Есть подтверждённые находки — штатный исход ревью.
OUTCOME_CONFIRMED = "confirmed_findings"

#: НОВАЯ СТУПЕНЬ (#1234): подтверждённых нет, но есть те, кого никто не смог
#: рассудить. Раньше этот отчёт попадал на ступень ниже и читался как чистый.
OUTCOME_UNRESOLVED = "unresolved_findings"

#: Кандидатов не было вовсе. «Нет данных», а не «находок нет»: харнесс v7
#: сдал шестьдесят таких отчётов (#745).
OUTCOME_NO_DATA = "no_data"

#: Единственная ступень, про которую правда, что находок нет.
OUTCOME_CLEAN = "clean"

#: Все ступени, от самой громкой к самой тихой. Порядок значим: он же —
#: порядок проверок в :func:`report_outcome`. Перечень публичный, потому что
#: полноту разбора проверяет тест перечислением, а не внимательность
#: читателя (тем же приёмом, что ``LOUD_GROUND_CODES`` в gate_grounds).
REPORT_OUTCOMES: tuple[str, ...] = (
    OUTCOME_INCOMPLETE,
    OUTCOME_CONFIRMED,
    OUTCOME_UNRESOLVED,
    OUTCOME_NO_DATA,
    OUTCOME_CLEAN,
)

#: Ступени, которые поверхности имеют право назвать чистотой. Ровно одна.
#:
#: Множеством, а не сравнением с одной константой, намеренно: сравнение
#: ``outcome == OUTCOME_CLEAN`` пришлось бы повторить в каждой поверхности, и
#: тогда «что считается чистым» снова стало бы тремя мнениями вместо одного
#: правила.
CLEAN_OUTCOMES: frozenset[str] = frozenset({OUTCOME_CLEAN})

#: Что поверхность печатает про ступень. Тексты здесь, а не в шаблонах, по
#: той же причине, по которой здесь же лежит и сама ступень: три поверхности,
#: одно правило. Ни один текст, кроме OUTCOME_CLEAN, не содержит слов о
#: чистоте или об отсутствии находок — это проверяется тестом.
_OUTCOME_LABELS: dict[str, str] = {
    OUTCOME_INCOMPLETE: "прогон неполный — не проверено, а не «чисто»",
    OUTCOME_CONFIRMED: "подтверждённые находки",
    OUTCOME_UNRESOLVED: (
        "неразрешённые находки: никто не смог их рассудить — это незаданный "
        "вопрос, а не «чисто»"
    ),
    OUTCOME_NO_DATA: "кандидатов не было вовсе — нет данных, а не «находок нет»",
    OUTCOME_CLEAN: "находок нет",
}


def report_outcome(
    *,
    confirmed: Sequence[Any],
    unresolved: Sequence[Any],
    incomplete: bool = False,
    raw_count: int = 0,
) -> str:
    """На какой ступени стоит отчёт машинного ревью.

    Порядок проверок — порядок :data:`REPORT_OUTCOMES`: первым называется то,
    что дороже всего пропустить. Отчёт с подтверждёнными И неразрешёнными
    находками стоит на ступени подтверждённых: обе видны читателю, а ступень
    называет самое громкое.

    ``unresolved`` не смешивается с ``confirmed`` ни здесь, ни где-либо ещё.
    Это своя ступень именно потому, что «никто не смог судить» и «судили и
    подтвердили» — разные утверждения о разной цене для автора.
    """
    if incomplete:
        return OUTCOME_INCOMPLETE
    if confirmed:
        return OUTCOME_CONFIRMED
    if unresolved:
        return OUTCOME_UNRESOLVED
    if (raw_count or 0) < 1:
        return OUTCOME_NO_DATA
    return OUTCOME_CLEAN


def outcome_label(outcome: str) -> str:
    """Строка, которую поверхность печатает про ступень.

    Неизвестная ступень не превращается в пустую строку: пустое место рядом
    с числом находок читается как «всё в порядке» — ровно та подмена, против
    которой написан весь модуль.
    """
    return _OUTCOME_LABELS.get(outcome, f"неизвестный исход отчёта: {outcome!r}")


def names_clean(outcome: str) -> bool:
    """Можно ли этой ступени говорить «находок нет».

    Единственная функция, которой поверхности задают этот вопрос. Пока он
    задавался каждой поверхностью самостоятельно — по длине
    ``findings_confirmed`` — ответ у трёх поверхностей был один и тот же и
    неверный.
    """
    return outcome in CLEAN_OUTCOMES


# ---------------------------------------------------------------------------
# Механический шаг: мутация, прогон, наблюдение
# ---------------------------------------------------------------------------

#: Тест упал под мутацией — находка настоящая. ЕДИНСТВЕННЫЙ исход, дающий
#: подтверждение, и дающий его доказательством, а не голосованием.
STEP_CONFIRMED = "mutation_killed_by_test"

#: Набор пережил мутацию. Это НЕ «находка ложная»: поведение может быть
#: верным, а покрытия под ним нет. Ответ, а не тишина.
STEP_UNCOVERED = "mutation_survived_uncovered"

#: Из формулировки находки мутация не выводится — шаг честно отказывается.
STEP_NO_MUTATION = "no_mutation_derived"

#: Дерево после шага оказалось грязным. Наблюдение, снятое над неизвестно
#: каким деревом, ничего не наблюдает, поэтому это отказ, а не результат.
STEP_DIRTY_TREE = "worktree_not_restored"

#: Мутация выведена, но НАБОР НЕ ГОНЯЛСЯ: живого зонда нет (не настроен),
#: или он не смог прогнать набор. Отдельный исход, а не «набор зелёный»:
#: непрогнанный набор и переживший мутацию набор — разные утверждения, и
#: путать их значило бы выдавать «непокрытый случай» за наблюдение там, где
#: не наблюдали ничего. Находку несут человеку — но с НАЗВАННОЙ мутацией,
#: которую он запустит сам, а не с пустыми руками.
STEP_NO_RUN = "suite_did_not_run"

#: Исходы шага, после которых находку несут человеку. Перечень публичный по
#: той же причине, что и REPORT_OUTCOMES.
STEP_OUTCOMES: tuple[str, ...] = (
    STEP_CONFIRMED,
    STEP_UNCOVERED,
    STEP_NO_MUTATION,
    STEP_DIRTY_TREE,
    STEP_NO_RUN,
)

#: Исходы, которые человека НЕ зовут: у находки уже есть ответ.
STEP_ANSWERED: frozenset[str] = frozenset({STEP_CONFIRMED, STEP_UNCOVERED})

#: Сколько прогонов набора шаг тратит на одну находку. Один. Шаг дешёвый или
#: его нет: прогон набора на каждую находку — это минуты, и цена вторая
#: перестаёт окупать разницу с человеком.
MAX_RUNS_PER_FINDING = 1

#: Расширения, за которыми шаг признаёт путь путём. Список закрытый: без него
#: «выводится ли мутация» решала бы форма строки, а не наличие файла.
_SOURCE_SUFFIXES = ("py", "html", "js", "ts", "sql", "toml", "yaml", "yml", "md")

_PATH = r"[\w./\-]+\.(?:" + "|".join(_SOURCE_SUFFIXES) + r")"

#: ``hub/services/x.py:120`` и ``hub/services/x.py:120-135``.
_FILE_COLON_LINES = re.compile(
    rf"(?P<file>{_PATH}):(?P<start>\d+)(?:\s*[-–—]\s*(?P<end>\d+))?"
)

#: ``hub/services/x.py, строки 120-135`` — как это пишут отчёты по-русски.
_FILE_WORD_LINES = re.compile(
    rf"(?P<file>{_PATH})[^\n\d]{{0,40}}?(?:строк\w*|line[s]?)\s*"
    rf"(?P<start>\d+)(?:\s*[-–—]\s*(?P<end>\d+))?",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class Mutation:
    """Правка, которую находка называет САМА.

    Ни файл, ни строки не берутся из головы: у неразрешённой записи нет ни
    ``locator``, ни ``file``, ни ``start_line`` — схема
    :class:`hub.models.MachineUnresolvedFinding` знает только ``title`` и
    ``why``. Поэтому место мутации вычитывается из её собственного текста, и
    текст, который места не назвал, мутации не даёт (:data:`STEP_NO_MUTATION`).
    """

    file: str
    start_line: int
    end_line: int
    #: Откуда взято место — ``title`` или ``why``. Человек, проверяющий вывод
    #: шага, должен видеть не только что мутировали, но и по какой фразе.
    source_field: str
    quote: str

    @property
    def name(self) -> str:
        """Имя мутации, годное для записи в наблюдение."""
        if self.end_line != self.start_line:
            return f"{self.file}:{self.start_line}-{self.end_line}"
        return f"{self.file}:{self.start_line}"


@dataclass(frozen=True)
class SuiteResult:
    """Что вернул прогон набора. Наблюдение, а не мнение.

    ``failed`` — ИМЕНА упавших тестов, не их число: наблюдение «упало 2»
    человеку не проверить, а ``tests/test_x.py::test_y`` он запустит сам.
    """

    failed: tuple[str, ...] = ()
    passed: int = 0

    @property
    def green(self) -> bool:
        return not self.failed


@dataclass(frozen=True)
class StepResult:
    """Исход механического шага и наблюдение под ним."""

    outcome: str
    observation: str
    mutation: Mutation | None = None
    #: Что шаг успел проверить. Едет с находкой к человеку, чтобы он не
    #: начинал с нуля (AC-4).
    checked: tuple[str, ...] = ()
    tree_clean: bool = True
    suite: SuiteResult | None = None

    @property
    def needs_human(self) -> bool:
        return self.outcome not in STEP_ANSWERED

    @property
    def confirms(self) -> bool:
        """Стала ли находка подтверждённой.

        Ровно один исход, и он — упавший тест. Свойство существует, чтобы
        вызывающий не сравнивал строки сам: сравнение, повторённое в двух
        местах, — это то, как «подтверждена» однажды разъедется с «упал тест».
        """
        return self.outcome == STEP_CONFIRMED


def derive_mutation(finding: Mapping[str, Any]) -> Mutation | None:
    """Мутация, названная самой находкой, или ``None``.

    ``None`` — полноправный ответ, а не ошибка: текст находки пишет модель, и
    текст без места мутации не даёт. Честный отказ здесь дешевле догадки:
    неверно выведенная мутация даёт ложный ответ ОБОИХ видов — «настоящая»
    там, где упал посторонний тест, и «непокрытый случай» там, где мутировали
    не то место.

    ``title`` смотрится раньше ``why``: заголовок называет сам дефект, а
    ``why`` — то, на чём не сошлись адъюдикаторы, и файл в нём может быть
    упомянут по совсем другому поводу.
    """
    for field_name in ("title", "why"):
        text = str(finding.get(field_name) or "")
        if not text:
            continue
        for pattern in (_FILE_COLON_LINES, _FILE_WORD_LINES):
            match = pattern.search(text)
            if match is None:
                continue
            start = int(match.group("start"))
            if start < 1:
                # Строка 0 — это не место, а неверно разобранный текст.
                continue
            raw_end = match.group("end")
            end = int(raw_end) if raw_end else start
            if end < start:
                end = start
            return Mutation(
                file=match.group("file"),
                start_line=start,
                end_line=end,
                source_field=field_name,
                quote=match.group(0),
            )
    return None


def mechanical_step(
    finding: Mapping[str, Any],
    run_suite: Callable[[Mutation], SuiteResult | None],
    *,
    already_checked: Sequence[str] = (),
    tree_is_clean: Callable[[], bool] | None = None,
) -> StepResult:
    """Применить мутацию, прогнать набор, назвать исход. Человека не звать.

    ``run_suite`` ПРИМЕНЯЕТ мутацию, гоняет набор и ОТКАТЫВАЕТ её. Прогон
    инъектирован, а не зашит, по двум причинам сразу: живой зонд — отдельная
    работа со своей песочницей, а решение об исходе обязано проверяться без
    настоящего прогона набора на каждый случай.

    ``run_suite`` вправе вернуть ``None`` — «прогнать не смог». Это НЕ
    зелёный набор: :data:`STEP_NO_RUN` говорит, что наблюдения нет вовсе, и
    несёт находку человеку с названной мутацией. Отсутствие зонда, зависший
    прогон и мутация, ломающая разбор файла, приходят сюда одной дверью:
    во всех трёх случаях сказать про находку по результату прогона нечего.

    ``tree_is_clean`` спрашивают ПОСЛЕ прогона — ровно тем приёмом, которым
    сегодня работали исполнители: снять правку, увидеть падение своего теста,
    вернуть файл, проверить ``git status``. Дерево, вернувшееся грязным,
    отменяет исход: наблюдение над неизвестным деревом — не наблюдение.

    Ничего не чинит и ничего не решает за человека: сюда не передаётся ни
    задача, ни вердикт.
    """
    checked = tuple(already_checked)
    title = str(finding.get("title") or "").strip() or "<без заголовка>"

    mutation = derive_mutation(finding)
    if mutation is None:
        # AC-4: отказ ЧЕСТНЫЙ — он называет, чего не хватило, и уносит с
        # собой то, что уже проверено. Находка, приехавшая к человеку без
        # этого списка, заставляет его начать с нуля.
        return StepResult(
            outcome=STEP_NO_MUTATION,
            observation=(
                f"мутация из находки не выводится: в тексте «{title}» нет "
                "файла со строкой, а неразрешённая запись своих полей "
                "locator/file/start_line не имеет. Шаг отказался, находка "
                "едет человеку как есть"
            ),
            checked=checked,
        )

    suite = run_suite(mutation)

    if suite is None:
        # Набор НЕ гонялся. Исход отдельный, потому что «не прогоняли» и
        # «прогнали, и ничего не упало» — разные утверждения: второе есть
        # наблюдение, первое — его отсутствие, и выдать одно за другое
        # значило бы объявить непокрытым случаем то, чего никто не смотрел.
        # Человека зовут, но не с пустыми руками: мутация НАЗВАНА, и её
        # можно применить руками ровно там, где сказано.
        return StepResult(
            outcome=STEP_NO_RUN,
            observation=(
                f"мутация {mutation.name} (по «{mutation.quote}» из поля "
                f"{mutation.source_field}) выведена, но набор под ней не "
                "гонялся: живого прогона нет. Исход не вынесен — находка "
                "едет человеку с названной мутацией"
            ),
            mutation=mutation,
            checked=checked + (f"мутация {mutation.name} выведена из текста",),
            suite=None,
        )

    if tree_is_clean is not None and not tree_is_clean():
        # Исход НЕ выносится: под грязным деревом одинаково правдоподобны
        # «упал наш тест» и «упало постороннее».
        return StepResult(
            outcome=STEP_DIRTY_TREE,
            observation=(
                f"после мутации {mutation.name} рабочее дерево осталось "
                "грязным — исход не выносится, наблюдение снято над "
                "неизвестным деревом. Находка едет человеку"
            ),
            mutation=mutation,
            checked=checked + (f"мутация {mutation.name} применена",),
            tree_clean=False,
            suite=suite,
        )

    if suite.failed:
        # AC-2: подтверждение — доказательством. Имена упавших тестов, а не
        # их число: человек должен уметь перезапустить ровно то, что упало.
        named = ", ".join(suite.failed)
        return StepResult(
            outcome=STEP_CONFIRMED,
            observation=(
                f"мутация {mutation.name} (по «{mutation.quote}» из поля "
                f"{mutation.source_field}) уронила тесты: {named}. Находка "
                "настоящая — подтверждена падением теста, не голосованием"
            ),
            mutation=mutation,
            checked=checked + (f"мутация {mutation.name} применена и откачена",),
            suite=suite,
        )

    # AC-3: зелёный набор — тоже ответ. НЕ «находка ложная»: поведение может
    # быть верным, а покрытия под ним нет, и это ровно тот случай, который
    # 09.09.2026 разошёлся пополам.
    return StepResult(
        outcome=STEP_UNCOVERED,
        observation=(
            f"мутация {mutation.name} (по «{mutation.quote}» из поля "
            f"{mutation.source_field}) пережила набор: {suite.passed} тестов "
            "прошли, ни один не упал. Это непокрытый случай — поведение "
            "может быть верным, но теста под ним нет"
        ),
        mutation=mutation,
        checked=checked + (f"мутация {mutation.name} применена и откачена",),
        suite=suite,
    )


