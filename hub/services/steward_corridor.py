"""Неразрешённая находка — это незаданный вопрос, а не чистота (#1234).

ЗАМЕР, ПОВТОРЁННЫЙ ДВАЖДЫ. Ранее по пяти отчётам (#163-#167): тринадцать
ПОДТВЕРЖДЁННЫХ находок, ни одна не оказалась настоящей, — и шесть
НЕРАЗРЕШЁННЫХ, настоящими оказались все шесть. 09.09.2026 замер повторён на
новых данных: из семи неразрешённых настоящими оказались шесть. Один и тот
же вывод двумя независимыми выборками: раздел ``unresolved`` — самый
урожайный источник настоящих дефектов из всего, что даёт машинное ревью.

И ЕДИНСТВЕННЫЙ, КОТОРОГО КОНТУР НЕ ВИДЕЛ. Отчёт с нулём подтверждённых и
непустым ``unresolved`` читался всеми поверхностями как «находок нет»:
карточка печатала «0 / N подтверждено из сырых», квитанция ревью —
«0 confirmed / N rejected», дайджест не показывал раздел вовсе. Блокировать
автоодобрение хаб уже умел (#1170, ``gate_grounds.unattended_blockers``) —
но молча. Молчаливый отказ и чистый отчёт для читателя неразличимы, и
09.09.2026 три задачи (#1158 с шестью неразрешёнными, #1171 с пятью, #1208
с четырьмя) пришлось разбирать вручную, задание за заданием.

ЛЕСТНИЦА ИСХОДОВ ОТЧЁТА. Отчёт стоит на одной названной ступени, и
только у ОДНОЙ из них есть право называться чистотой. Ступень выводится в
одном месте, потому что читателей у неё трое — карточка, дайджест и
квитанция ревью — и три описания одного правила разъезжаются ровно так, как
разъехались бы пять громких оснований, если бы их не свели в
``gate_grounds`` (#1147). Разъезжается при этом тот, который мягче: правило,
добавленное в одну поверхность и забытое в двух, тихо возвращает «чисто»
туда, откуда его убирали.

Механический шаг перед эскалацией (мутация, названная находкой, и прогон
набора) решением владельца от 17.09.2026 вынесен в #1278: он исполняет код
проекта, и ему нужна песочница, а не хост хаба.

ГРАНИЦА, КОТОРУЮ ЗДЕСЬ НЕ ПЕРЕХОДЯТ. Неразрешённая находка — это НЕ
подтверждённая находка. Приравнять их значило бы заставить автора отвечать
за то, в чём ревьюер сам не сошёлся: голосование в подтверждение не
превращается ни при каком числе голосов. Адъюдикация внутри харнесса при
этом не отменяется и не переписывается.
"""

from __future__ import annotations

from typing import Any, Sequence


# ---------------------------------------------------------------------------
# Лестница исходов отчёта
# ---------------------------------------------------------------------------

#: Прогон не доехал. «Ноль находок на оборванном прогоне» — это «не
#: проверено», а не «чисто» (#549).
OUTCOME_INCOMPLETE = "incomplete_run"

#: Есть подтверждённые находки — штатный исход ревью.
OUTCOME_CONFIRMED = "confirmed_findings"

#: НОВАЯ СТУПЕНЬ (#1234): подтверждённых нет, но есть те, кого никто не смог
#: рассудить. Раньше этот отчёт попадал на ступень ниже и читался как чистый.
OUTCOME_UNRESOLVED = "unresolved_findings"

#: Кандидатов не было вовсе. «Нет данных», а не «находок нет»: харнесс v7
#: сдал шестьдесят таких отчётов (#745).
OUTCOME_NO_DATA = "no_data"

#: Единственная ступень, про которую правда, что находок нет.
OUTCOME_CLEAN = "clean"

#: Все ступени, от самой громкой к самой тихой. Порядок значим: он же —
#: порядок проверок в :func:`report_outcome`. Перечень публичный, потому что
#: полноту разбора проверяет тест перечислением, а не внимательность
#: читателя (тем же приёмом, что ``LOUD_GROUND_CODES`` в gate_grounds).
REPORT_OUTCOMES: tuple[str, ...] = (
    OUTCOME_INCOMPLETE,
    OUTCOME_CONFIRMED,
    OUTCOME_UNRESOLVED,
    OUTCOME_NO_DATA,
    OUTCOME_CLEAN,
)

#: Ступени, которые поверхности имеют право назвать чистотой. Ровно одна.
#:
#: Множеством, а не сравнением с одной константой, намеренно: сравнение
#: ``outcome == OUTCOME_CLEAN`` пришлось бы повторить в каждой поверхности, и
#: тогда «что считается чистым» снова стало бы тремя мнениями вместо одного
#: правила.
CLEAN_OUTCOMES: frozenset[str] = frozenset({OUTCOME_CLEAN})

#: Что поверхность печатает про ступень. Тексты здесь, а не в шаблонах, по
#: той же причине, по которой здесь же лежит и сама ступень: три поверхности,
#: одно правило. Ни один текст, кроме OUTCOME_CLEAN, не содержит слов о
#: чистоте или об отсутствии находок — это проверяется тестом.
_OUTCOME_LABELS: dict[str, str] = {
    OUTCOME_INCOMPLETE: "прогон неполный — не проверено, а не «чисто»",
    OUTCOME_CONFIRMED: "подтверждённые находки",
    OUTCOME_UNRESOLVED: (
        "неразрешённые находки: никто не смог их рассудить — это незаданный "
        "вопрос, а не «чисто»"
    ),
    OUTCOME_NO_DATA: "кандидатов не было вовсе — нет данных, а не «находок нет»",
    OUTCOME_CLEAN: "находок нет",
}


def report_outcome(
    *,
    confirmed: Sequence[Any],
    unresolved: Sequence[Any],
    incomplete: bool = False,
    raw_count: int = 0,
) -> str:
    """На какой ступени стоит отчёт машинного ревью.

    Порядок проверок — порядок :data:`REPORT_OUTCOMES`: первым называется то,
    что дороже всего пропустить. Отчёт с подтверждёнными И неразрешёнными
    находками стоит на ступени подтверждённых: обе видны читателю, а ступень
    называет самое громкое.

    ``unresolved`` не смешивается с ``confirmed`` ни здесь, ни где-либо ещё.
    Это своя ступень именно потому, что «никто не смог судить» и «судили и
    подтвердили» — разные утверждения о разной цене для автора.
    """
    if incomplete:
        return OUTCOME_INCOMPLETE
    if confirmed:
        return OUTCOME_CONFIRMED
    if unresolved:
        return OUTCOME_UNRESOLVED
    if (raw_count or 0) < 1:
        return OUTCOME_NO_DATA
    return OUTCOME_CLEAN


def outcome_label(outcome: str) -> str:
    """Строка, которую поверхность печатает про ступень.

    Неизвестная ступень не превращается в пустую строку: пустое место рядом
    с числом находок читается как «всё в порядке» — ровно та подмена, против
    которой написан весь модуль.
    """
    return _OUTCOME_LABELS.get(outcome, f"неизвестный исход отчёта: {outcome!r}")


def names_clean(outcome: str) -> bool:
    """Можно ли этой ступени говорить «находок нет».

    Единственная функция, которой поверхности задают этот вопрос. Пока он
    задавался каждой поверхностью самостоятельно — по длине
    ``findings_confirmed`` — ответ у трёх поверхностей был один и тот же и
    неверный.
    """
    return outcome in CLEAN_OUTCOMES
